import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { access, mkdtemp, mkdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { promisify } from "node:util";
import { after, test } from "node:test";

import type { Finding, ScanResult } from "../src/domain.js";
import type { RegistryV2Rule } from "../src/registry.js";
import {
  buildDependabotConfig,
  buildDependabotUpdates,
  dependabotDirectory,
} from "../src/dependabot-config.js";

const execute = promisify(execFile);
const cli = resolve("dist/src/cli.js");
const roots: string[] = [];

after(async () => {
  await Promise.all(roots.map((root) => rm(root, { recursive: true, force: true })));
});

function scanResult(findings: Finding[]): ScanResult {
  return {
    schemaVersion: "evergreen.scan.v1",
    root: "/repo",
    scannedAt: "2026-01-01T00:00:00.000Z",
    diagnostics: [],
    findings,
  };
}

function finding(ruleId: string, path: string): Finding {
  return {
    id: `${ruleId}:${path}`,
    ruleId,
    detector: "npm",
    title: "t",
    summary: "s",
    severity: "high",
    confidence: "exact",
    location: { path, line: 1 },
    sources: [],
  };
}

function rule(partial: Partial<RegistryV2Rule> & Pick<RegistryV2Rule, "id" | "purl">): RegistryV2Rule {
  return {
    ecosystem: "npm",
    vers: "vers:npm/*",
    event: "deprecated",
    title: "t",
    summary: "s",
    severity: "high",
    sources: [{ title: "s", url: "https://example.com" }],
    provenance: { observedAt: "2026-01-01", reviewedAt: "2026-01-01", reviewer: "test" },
    ...partial,
  };
}

test("dependabotDirectory maps repository paths to Dependabot directories", () => {
  assert.equal(dependabotDirectory("package.json"), "/");
  assert.equal(dependabotDirectory("apps/web/package.json"), "/apps/web");
  assert.equal(dependabotDirectory(".github/workflows/ci.yml"), "/");
  assert.equal(dependabotDirectory(".github/workflows/sub/ci.yml"), "/");
  assert.equal(dependabotDirectory(".github/actions/checkout/action.yml"), "/.github/actions/checkout");
});

test("buildDependabotUpdates groups deprecated packages per ecosystem and directory and skips prose", () => {
  const mavenRule = rule({ id: "maven.package.commons-text-ri.eol", ecosystem: "java", purl: "pkg:maven/org.apache.commons/commons-text@1.10.0" });
  const entries = buildDependabotUpdates(scanResult([
    finding("npm.package.node-sass.eol", "package.json"),
    finding("npm.package.jade.deprecated", "packages/app/package.json"),
    finding("npm.package.jade.deprecated", "packages/app/views.jade"),
    finding("maven.package.commons-text-ri.eol", "build.gradle"),
    finding("maven.package.commons-text-ri.eol", "src/app/pom.xml"),
    finding("nodejs.runtime.eol-18", "package.json"),
  ]), [
    rule({ id: "npm.package.node-sass.eol", purl: "pkg:npm/node-sass" }),
    rule({ id: "npm.package.jade.deprecated", purl: "pkg:npm/jade" }),
    mavenRule,
    rule({
      id: "nodejs.runtime.eol-18",
      ecosystem: "nodejs",
      purl: "pkg:generic/nodejs",
    }),
  ]);
  assert.deepEqual(entries.map((entry) => [entry.packageEcosystem, entry.directory, entry.patterns]), [
    ["gradle", "/", ["org.apache.commons:commons-text"]],
    ["maven", "/src/app", ["org.apache.commons:commons-text"]],
    ["npm", "/", ["node-sass"]],
    ["npm", "/packages/app", ["jade"]],
  ]);
});

test("buildDependabotConfig renders deterministic YAML with grouped patterns", () => {
  const rules = [
    rule({ id: "npm.package.node-sass.eol", purl: "pkg:npm/node-sass" }),
    rule({ id: "npm.package.jade.deprecated", purl: "pkg:npm/jade", replacement: "pug" }),
  ];
  const forward = buildDependabotConfig(scanResult([
    finding("npm.package.node-sass.eol", "package.json"),
    finding("npm.package.jade.deprecated", "package.json"),
  ]), rules);
  const reverse = buildDependabotConfig(scanResult([
    finding("npm.package.jade.deprecated", "package.json"),
    finding("npm.package.node-sass.eol", "package.json"),
  ]), [...rules].reverse());
  assert.equal(forward, reverse);
  assert.equal(forward, `# Generated by Evergreen from repository lifecycle findings.
# Review before merging into .github/dependabot.yml; Evergreen does not edit files.
version: 2
updates:
  - package-ecosystem: npm
    directory: "/"
    schedule:
      interval: weekly
    groups:
      evergreen-deprecated-packages:
        applies-to: version-updates
        patterns:
          - "jade"
          - "node-sass"
`);
});

test("runtime findings alone produce no updates entry", () => {
  const yaml = buildDependabotConfig(scanResult([finding("nodejs.runtime.eol-18", "package.json")]), [
    rule({ id: "nodejs.runtime.eol-18", ecosystem: "nodejs", purl: "pkg:generic/nodejs" }),
  ]);
  assert.ok(!yaml.includes("package-ecosystem:"));
  assert.ok(!yaml.includes("updates:"));
});

test("a scan with no mapped findings prints comments only, because Dependabot needs at least one entry", () => {
  const yaml = buildDependabotConfig(scanResult([]), []);
  assert.equal(yaml, `# Generated by Evergreen from repository lifecycle findings.
# Review before merging into .github/dependabot.yml; Evergreen does not edit files.
# Nothing was found in this scan: no deprecated packages with a mapped
# package-ecosystem, so there is no updates entry to copy. Dependabot
# requires at least one entry, so keep your existing dependabot.yml.
`);
});

test("the dependabot-config command prints multi-ecosystem YAML only and does not write files", async () => {
  const directory = await mkdtemp(join(tmpdir(), "evergreen-dependabot-"));
  roots.push(directory);
  await writeFile(
    join(directory, "package.json"),
    JSON.stringify({ name: "demo", dependencies: { "node-sass": "4.14.1" } }),
  );
  const workflows = join(directory, ".github", "workflows");
  await mkdir(workflows, { recursive: true });
  await writeFile(join(workflows, "ci.yml"), [
    "name: ci",
    "on: push",
    "jobs:",
    "  build:",
    "    runs-on: ubuntu-latest",
    "    steps:",
    "      - uses: actions/checkout@v2",
  ].join("\n"));
  const { stdout, stderr } = await execute(process.execPath, [cli, "dependabot-config", directory]);
  assert.equal(stderr, "");
  assert.ok(stdout.includes("package-ecosystem: npm"));
  assert.ok(stdout.includes("package-ecosystem: github-actions"));
  assert.ok(stdout.includes('"node-sass"'));
  assert.ok(stdout.includes('"actions/checkout"'));
  await assert.rejects(access(join(directory, ".github", "dependabot.yml")));
});
