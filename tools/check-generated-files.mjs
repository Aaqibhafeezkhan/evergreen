// Fails a pull request that commits a build output back into the repository.
//
//   node tools/check-generated-files.mjs [--base <git-ref>]
//
// The list of outputs comes from the inventory in docs/generated-files.md: every path that page
// marks Build time or Release time must not be added by a pull request. A new file that carries a
// generated-file marker in its opening lines is refused too, so an output under a new name is
// caught as well. A pull request must also leave the Release time outputs (CHANGELOG.md, the action
// bundle) alone, even to edit them, unless it is the release pull request and passes `--release`.
//
// It reads git and file contents only: no network, no child processes other than git, and it never
// executes repository or fixture code. Exit codes: 0 when nothing offending was added, 1 when a
// generated file was added, 2 when the command cannot run (bad usage, or a base ref git cannot
// diff against).

import { execFileSync } from "node:child_process";
import { closeSync, openSync, readSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

export const INVENTORY = "docs/generated-files.md";
export const DEFAULT_BASE = "origin/main";

/** How many opening lines of an added file the marker scan reads. */
export const MARKER_LINES = 10;

/** Bytes read from each added file; enough for MARKER_LINES of any realistic header. */
const HEAD_BYTES = 8 * 1024;

/**
 * Paths the inventory marks Build time or Release time. A pull request must not add one: these are
 * written by a tool, not by hand, and committing them brings back the conflicts the inventory
 * exists to remove. `directory: true` matches everything under `path`.
 */
export const GENERATED_PATHS = Object.freeze([
  { path: "docs/llms-full.txt", directory: false, target: "Build time", generator: "npm run build:llms" },
  { path: "docs/sitemap.xml", directory: false, target: "Build time", generator: "npm run build:reference" },
  { path: "docs/rules/index.md", directory: false, target: "Build time", generator: "npm run build:reference" },
  { path: "docs/dashboard/data.json", directory: false, target: "Build time", generator: "npm run build:dashboard" },
  { path: "docs/api/v1", directory: true, target: "Build time", generator: "npm run build:data-api" },
  {
    path: "src/commands/index.generated.ts",
    directory: false,
    target: "Build time",
    generator: "node tools/generate-commands-index.mjs",
  },
  { path: "dist/action/index.js", directory: false, target: "Release time", generator: "npm run build:action" },
  { path: "CHANGELOG.md", directory: false, target: "Release time", generator: "node dist/tools/changelog.js --write" },
]);

/** Opening-line markers that identify an output a tool writes. */
export const MARKER_PATTERNS = Object.freeze([
  /@generated\b/i,
  /\bgenerated by\b/i,
  /\bauto-?generated\b/i,
  /\bthis (?:file|page) is generated\b/i,
  /\bdo not edit\b/i,
  /\bcode generated\b.*\bdo not edit\b/i,
]);

const normalize = (value) => value.replace(/^\.\//, "").replace(/^\/+/, "").replace(/\/+$/, "");

/** The inventory entry a path matches, or undefined. */
export function matchGeneratedPath(filePath) {
  const target = normalize(filePath);
  for (const entry of GENERATED_PATHS) {
    const candidate = normalize(entry.path);
    if (entry.directory ? target === candidate || target.startsWith(`${candidate}/`) : target === candidate) {
      return entry;
    }
  }
  return undefined;
}

/**
 * The files a change set touches in any way (added, modified, deleted, renamed) that the inventory marks
 * Release time. Only the release pull request may change these; every other change adds a fragment under
 * `changes/` instead.
 */
export function touchedReleaseFiles(base, root = process.cwd()) {
  const output = execFileSync("git", ["-C", root, "diff", "--name-only", "-M", base, "HEAD"], {
    encoding: "utf8",
  });
  return output
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && matchGeneratedPath(line)?.target === "Release time")
    .sort((left, right) => left.localeCompare(right));
}

/** The message for a Release time output a pull request edited. */
export function describeRelease(file) {
  const entry = matchGeneratedPath(file);
  return `"${file}" is generated at ${entry?.target} (see ${INVENTORY}); only the release pull request (title starts with "chore: release") may change it. Add a fragment under changes/ instead (see changes/README.md).`;
}

/** The first opening line that carries a generated-file marker, or undefined. */
export function markerIn(text) {
  for (const line of text.split(/\r?\n/).slice(0, MARKER_LINES)) {
    for (const pattern of MARKER_PATTERNS) {
      if (pattern.test(line)) return line.trim();
    }
  }
  return undefined;
}

/** The first bytes of a file, without reading the rest of it. */
function readHead(file) {
  const descriptor = openSync(file, "r");
  try {
    const buffer = Buffer.alloc(HEAD_BYTES);
    const read = readSync(descriptor, buffer, 0, HEAD_BYTES, 0);
    return buffer.subarray(0, read);
  } finally {
    closeSync(descriptor);
  }
}

/**
 * The files a change set adds, or moves while editing. A pure rename is not an addition: its content already
 * exists in the base commit, so a header that says the file was generated (a lockfile, for example) does not
 * mean this pull request introduced a build output. A rename whose content changed is inspected at its new path.
 */
export function addedFiles(base, root = process.cwd()) {
  const output = execFileSync("git", ["-C", root, "diff", "--name-status", "-M", base, "HEAD"], {
    encoding: "utf8",
  });
  const files = [];
  for (const line of output.split("\n")) {
    const fields = line.split("\t");
    const status = fields[0] ?? "";
    if (status === "A") files.push(fields[1]?.trim() ?? "");
    else if (status.startsWith("R") && status !== "R100") files.push(fields[2]?.trim() ?? "");
  }
  return files.filter((line) => line.length > 0).sort((left, right) => left.localeCompare(right));
}

/** Everything wrong with the added files: an inventoried path, or a generated-file marker. */
export function inspectAdditions(files, options = {}) {
  const root = options.root ?? process.cwd();
  const findings = [];
  for (const file of files) {
    const entry = matchGeneratedPath(file);
    if (entry) {
      findings.push({ path: file, kind: "path", target: entry.target, generator: entry.generator });
      continue;
    }

    let head;
    try {
      head = readHead(join(root, file));
    } catch {
      continue;
    }
    if (head.includes(0)) continue;
    const marker = markerIn(head.toString("utf8"));
    if (marker !== undefined) findings.push({ path: file, kind: "marker", marker });
  }
  return findings;
}

/** The message for one finding, naming the source to change and the command to regenerate it. */
export function describeFinding(finding) {
  if (finding.kind === "path") {
    return `"${finding.path}" is generated at ${finding.target} (see ${INVENTORY}); do not commit it. Regenerate it locally with: ${finding.generator}.`;
  }
  return `"${finding.path}" looks generated: its header says "${finding.marker}". Commit the source, not the output (see ${INVENTORY}).`;
}

export const USAGE = "usage: node tools/check-generated-files.mjs [--base <git-ref>] [--release]";

export function main(args = process.argv.slice(2)) {
  if (args.includes("--help") || args.includes("-h")) {
    process.stdout.write(
      `${USAGE}\n\nCompares the added files against ${INVENTORY}, and refuses any edit to a Release time output unless --release is given (the release pull request).\n`,
    );
    return 0;
  }

  const baseIndex = args.indexOf("--base");
  const base = baseIndex >= 0 && args[baseIndex + 1] ? args[baseIndex + 1] : DEFAULT_BASE;

  let files;
  try {
    files = addedFiles(base);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    process.stderr.write(`check-generated-files: cannot diff against "${base}": ${message.split("\n")[0]}\n${USAGE}\n`);
    return 2;
  }

  const findings = inspectAdditions(files);
  const release = args.includes("--release");
  let touched;
  try {
    touched = release ? [] : touchedReleaseFiles(base);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    process.stderr.write(`check-generated-files: cannot diff against "${base}": ${message.split("\n")[0]}\n${USAGE}\n`);
    return 2;
  }
  if (findings.length === 0 && touched.length === 0) {
    process.stdout.write(
      `No generated files were added (${files.length} added file(s) checked against ${GENERATED_PATHS.length} inventoried paths).\n`,
    );
    return 0;
  }

  const annotate = process.env.GITHUB_ACTIONS === "true";
  for (const file of touched) {
    const message = describeRelease(file);
    process.stderr.write(annotate ? `::error file=${file}::${message}\n` : `error: ${message}\n`);
  }
  for (const finding of findings) {
    const message = describeFinding(finding);
    process.stderr.write(annotate ? `::error file=${finding.path}::${message}\n` : `error: ${message}\n`);
  }
  process.stderr.write(
    `\n${findings.length} generated file(s) added, ${touched.length} release output(s) edited. Commit the source and regenerate locally; do not commit the output.\n`,
  );
  return 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.exitCode = main();
}
