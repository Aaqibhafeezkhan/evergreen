import assert from "node:assert/strict";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";

import type { RegistryV2Rule } from "../src/registry.js";
import { buildCalendar, buildWeeklyPost, loadRules, loadRulesFromBundle, main, renderAtom, renderIcs, renderMarkdown, renderRss, renderWeeklyPost } from "../tools/eol-calendar.js";

const rule = (id: string, deadline: string | undefined, title = `Title ${id}`): RegistryV2Rule => ({
  id,
  ecosystem: "demo",
  purl: "pkg:generic/demo",
  vers: "vers:semver/<2.0.0",
  event: "end-of-life",
  title,
  summary: "s",
  severity: "high",
  ...(deadline ? { deadline } : {}),
  sources: [{ title: "t", url: "https://example.com/x" }],
  provenance: { observedAt: "2026-10-16", reviewedAt: "2026-10-16", reviewer: "r" },
});

const rules = [rule("a.late", "2027-04-30"), rule("a.soon", "2026-11-12"), rule("a.edge", "2027-04-16"), rule("a.past", "2026-10-01"), rule("a.old", "2025-01-01"), rule("a.none", undefined)];

test("windows the deadlines around the reference day, in date order", () => {
  const calendar = buildCalendar(rules, "2026-10-16");
  assert.deepEqual(calendar.upcoming.map((entry) => entry.ruleId), ["a.soon", "a.edge"]);
  assert.deepEqual(calendar.recent.map((entry) => entry.ruleId), ["a.past"]);
  assert.equal(calendar.until, "2027-04-16");
  assert.deepEqual(buildCalendar(rules, "2026-10-16", 7).upcoming.map((entry) => entry.ruleId), ["a.soon", "a.edge", "a.late"]);
});

test("a deadline on the reference day is upcoming, not recent", () => {
  const calendar = buildCalendar([rule("a.today", "2026-10-16")], "2026-10-16");
  assert.equal(calendar.upcoming.length, 1);
  assert.equal(calendar.recent.length, 0);
});

test("rejects a reference day that is not a date", () => {
  assert.throws(() => buildCalendar(rules, "tomorrow"), /not a date/);
});

test("renders Markdown with escaped cells and an empty message", () => {
  const text = renderMarkdown(buildCalendar([rule("a.soon", "2026-11-12", "A | B")], "2026-10-16"));
  assert.match(text, /\| 2026-11-12 \| demo \| A \\\| B \| high \| `a.soon` \|/);
  assert.match(renderMarkdown(buildCalendar([], "2026-10-16")), /None in the registry\./);
});

test("builds a weekly post from the days before today, without today", () => {
  const post = buildWeeklyPost([...rules, rule("a.eight", "2026-10-09"), rule("a.week", "2026-10-12")], "2026-10-16");
  assert.equal(post.since, "2026-10-09");
  assert.equal(post.until, "2026-10-15");
  assert.deepEqual(post.entries.map((entry) => entry.ruleId), ["a.eight", "a.week"]);
});

test("renders a draft with sources and a review checklist, and nothing for an empty window", () => {
  const text = renderWeeklyPost(buildWeeklyPost([rule("a.week", "2026-10-12", "Week end")], "2026-10-16"));
  assert.match(text, /^<!-- Draft generated by Evergreen\./);
  assert.match(text, /^# What went end of life this week \(2026-10-09 to 2026-10-15\)$/m);
  assert.match(text, /`a\.week`/);
  assert.match(text, /\[source\]\(https:\/\/example\.com\/x\)/);
  assert.match(text, /## Before publishing/);
  assert.match(text, /nothing is posted automatically/);

  const empty = renderWeeklyPost(buildWeeklyPost([], "2026-10-16"));
  assert.match(empty, /Delete this draft/);
});

test("renders a deterministic iCalendar file with CRLF lines and all-day events", () => {
  const ics = renderIcs(buildCalendar([rule("a.soon", "2026-11-12", "Ends, soon; really")], "2026-10-16"));
  assert.equal(ics, renderIcs(buildCalendar([rule("a.soon", "2026-11-12", "Ends, soon; really")], "2026-10-16")));
  assert.ok(ics.startsWith("BEGIN:VCALENDAR\r\n") && ics.endsWith("END:VCALENDAR\r\n"));
  assert.match(ics, /DTSTART;VALUE=DATE:20261112\r\nDTEND;VALUE=DATE:20261113\r\n/);
  assert.match(ics, /SUMMARY:Ends\\, soon\; really\r\n/);
  assert.match(ics, /UID:a\.soon@evergreen\r\n/);
});

test("renders a deterministic RSS 2.0 feed with escaped entities and item metadata", () => {
  const calendar = buildCalendar([rule("a.soon", "2026-11-12", "Ends <soon> & 'really'")], "2026-10-16");
  const rss = renderRss(calendar);
  assert.equal(rss, renderRss(calendar));
  assert.ok(rss.startsWith('<?xml version="1.0" encoding="UTF-8"?>\n<rss version="2.0"'));
  assert.ok(rss.endsWith("</rss>\n"));
  assert.match(rss, /<title>Evergreen Lifecycle Calendar<\/title>/);
  assert.match(rss, /<lastBuildDate>Fri, 16 Oct 2026 00:00:00 GMT<\/lastBuildDate>/);
  assert.match(rss, /<title>Ends &lt;soon&gt; &amp; &apos;really&apos;<\/title>/);
  assert.match(rss, /<guid isPermaLink="false">a\.soon@evergreen<\/guid>/);
  assert.match(rss, /<pubDate>Thu, 12 Nov 2026 00:00:00 GMT<\/pubDate>/);
  assert.match(rss, /<category>demo<\/category>/);
});

test("renders a deterministic Atom 1.0 feed with author, entries, and categories", () => {
  const calendar = buildCalendar([rule("a.soon", "2026-11-12", "Ends <soon> & 'really'")], "2026-10-16");
  const atom = renderAtom(calendar);
  assert.equal(atom, renderAtom(calendar));
  assert.ok(atom.startsWith('<?xml version="1.0" encoding="UTF-8"?>\n<feed xmlns="http://www.w3.org/2005/Atom">'));
  assert.ok(atom.endsWith("</feed>\n"));
  assert.match(atom, /<title>Evergreen Lifecycle Calendar<\/title>/);
  assert.match(atom, /<updated>2026-10-16T00:00:00Z<\/updated>/);
  assert.match(atom, /<author>\s*<name>Evergreen<\/name>\s*<\/author>/);
  assert.match(atom, /<title>Ends &lt;soon&gt; &amp; &apos;really&apos;<\/title>/);
  assert.match(atom, /<id>urn:evergreen:rule:a\.soon<\/id>/);
  assert.match(atom, /<updated>2026-11-12T00:00:00Z<\/updated>/);
  assert.match(atom, /<category term="demo"\/>/);
});

test("loads rules from a data bundle file", async () => {
  const directory = await mkdtemp(join(tmpdir(), "evergreen-bundle-"));
  try {
    const bundlePath = join(directory, "bundle.json");
    const fakeBundle = {
      manifest: { schemaVersion: "evergreen.data-bundle.v1" },
      files: {
        "registry/demo.json": {
          schemaVersion: "evergreen.registry.v2",
          ecosystem: "demo",
          rules: [rule("b.bundle", "2026-12-01", "Bundle rule")],
        },
      },
    };
    await writeFile(bundlePath, JSON.stringify(fakeBundle));
    const loaded = await loadRulesFromBundle(bundlePath);
    assert.equal(loaded.length, 1);
    assert.equal(loaded[0]!.id, "b.bundle");

    const loadedViaSource = await loadRules(bundlePath);
    assert.equal(loadedViaSource.length, 1);
    assert.equal(loadedViaSource[0]!.id, "b.bundle");

    const outDir = join(directory, "out");
    assert.equal(await main(["--bundle", bundlePath, "--today", "2026-10-16", "--out-dir", outDir]), 0);
    assert.match(await readFile(join(outDir, "eol-calendar.rss"), "utf8"), /<title>Bundle rule<\/title>/);
    assert.match(await readFile(join(outDir, "eol-calendar.atom"), "utf8"), /<title>Bundle rule<\/title>/);
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
});

test("--post-days writes a weekly draft, and only then, and rejects a non-positive window", async () => {
  const directory = await mkdtemp(join(tmpdir(), "evergreen-post-"));
  try {
    assert.equal(await main(["--today", "2026-10-29", "--out-dir", directory]), 0);
    await assert.rejects(readFile(join(directory, "weekly-post.md")), /ENOENT/);

    assert.equal(await main(["--today", "2026-10-29", "--post-days", "7", "--out-dir", directory]), 0);
    const draft = await readFile(join(directory, "weekly-post.md"), "utf8");
    assert.match(draft, /^<!-- Draft generated/);
    assert.match(draft, /## Before publishing/);

    await assert.rejects(main(["--today", "2026-10-29", "--post-days", "0", "--out-dir", directory]), /positive whole number/);
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
});

test("the real registry loads and the command writes all calendar and feed files", async () => {
  assert.ok((await loadRules()).length > 100);
  const directory = await mkdtemp(join(tmpdir(), "evergreen-calendar-"));
  try {
    assert.equal(await main(["--today", "2026-10-16", "--out-dir", directory]), 0);
    assert.match(await readFile(join(directory, "eol-calendar.md"), "utf8"), /^# Lifecycle calendar/);
    assert.match(await readFile(join(directory, "eol-calendar.ics"), "utf8"), /^BEGIN:VCALENDAR/);
    assert.match(await readFile(join(directory, "eol-calendar.rss"), "utf8"), /^<\?xml version="1.0" encoding="UTF-8"\?>\n<rss/);
    assert.match(await readFile(join(directory, "eol-calendar.atom"), "utf8"), /^<\?xml version="1.0" encoding="UTF-8"\?>\n<feed/);
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
});
