import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { test } from "node:test";
import { pathToFileURL } from "node:url";

import { parse } from "yaml";

const toolPath = resolve("tools/check-generated-files.mjs");
const workflowPath = resolve(".github/workflows/ci.yml");

interface Finding {
  path: string;
  kind: "path" | "marker";
  target?: string;
  generator?: string;
  marker?: string;
}

const tool = (await import(pathToFileURL(toolPath).href)) as {
  INVENTORY: string;
  DEFAULT_BASE: string;
  MARKER_LINES: number;
  GENERATED_PATHS: readonly { path: string; directory: boolean; target: string; generator: string }[];
  matchGeneratedPath: (filePath: string) => { path: string; target: string; generator: string } | undefined;
  markerIn: (text: string) => string | undefined;
  inspectAdditions: (files: readonly string[], options?: { root?: string }) => Finding[];
  addedFiles: (base: string, root?: string) => string[];
  describeFinding: (finding: Finding) => string;
  main: (args?: readonly string[]) => number;
};

function git(root: string, ...args: string[]): string {
  return execFileSync("git", ["-C", root, ...args], { encoding: "utf8" });
}

function commit(root: string, message: string): void {
  git(root, "-c", "user.name=Test", "-c", "user.email=test@example.com", "commit", "-m", message, "--no-gpg-sign");
}

function repository(): string {
  const root = mkdtempSync(join(tmpdir(), "evergreen-generated-files-"));
  git(root, "init", "-q", "-b", "main");
  writeFileSync(join(root, "README.md"), "# base\n");
  git(root, "add", ".");
  commit(root, "base");
  return root;
}

function runTool(root: string, ...args: string[]) {
  return spawnSync(process.execPath, [toolPath, ...args], { cwd: root, encoding: "utf8" });
}

test("the list covers every Build time and Release time output in the inventory", () => {
  const inventory = readFileSync(resolve(tool.INVENTORY), "utf8");
  const forbidden = new Set<string>();
  for (const row of inventory.split("\n").filter((line) => line.trim().startsWith("|"))) {
    const cells = row.split("|").map((cell) => cell.trim());
    if (cells.length < 8) continue;
    const pathCell = cells[1] ?? "";
    const targetCell = cells[6] ?? "";
    if (!/^(Build time|Release time)/.test(targetCell)) continue;
    for (const match of pathCell.matchAll(/`([^`]+)`/g)) {
      const path = (match[1] ?? "").replace(/\/+$/, "");
      if (path.length > 0) forbidden.add(path);
    }
  }

  assert.ok(forbidden.size > 0, "the inventory has no Build time or Release time rows");
  const covered = new Set(tool.GENERATED_PATHS.map((entry) => entry.path.replace(/\/+$/, "")));
  for (const path of forbidden) {
    assert.ok(
      covered.has(path),
      `${path} is Build time or Release time in ${tool.INVENTORY} but missing from GENERATED_PATHS`,
    );
  }
});

test("matchGeneratedPath matches exact paths and whole directories only", () => {
  assert.equal(tool.matchGeneratedPath("docs/llms-full.txt")?.target, "Build time");
  assert.equal(tool.matchGeneratedPath("./docs/llms-full.txt")?.target, "Build time");
  assert.equal(tool.matchGeneratedPath("docs/api/v1/index.json")?.target, "Build time");
  assert.equal(tool.matchGeneratedPath("docs/api/v1")?.target, "Build time");
  assert.equal(tool.matchGeneratedPath("dist/action/index.js")?.target, "Release time");
  assert.equal(tool.matchGeneratedPath("docs/api/v10/index.json"), undefined);
  assert.equal(tool.matchGeneratedPath("docs/rules/example.md"), undefined);
  assert.equal(tool.matchGeneratedPath("src/commands/index.ts"), undefined);
});

test("markerIn reads only the opening lines and ignores ordinary content", () => {
  assert.match(tool.markerIn("// Generated by tools/build.js. Do not edit by hand.\n") ?? "", /Generated by/);
  assert.equal(
    tool.markerIn("#!/usr/bin/env node\n# This file is generated from registry.json.\n"),
    "# This file is generated from registry.json.",
  );
  assert.equal(tool.markerIn("// @generated\n"), "// @generated");
  assert.equal(tool.markerIn("A normal source file.\n"), undefined);
  assert.equal(tool.markerIn(`${"\n".repeat(tool.MARKER_LINES + 5)}DO NOT EDIT\n`), undefined);
});

test("the command refuses inventoried paths, directory outputs, and marked new files", () => {
  const root = repository();
  const base = git(root, "rev-parse", "HEAD").trim();
  mkdirSync(join(root, "docs", "api", "v1"), { recursive: true });
  mkdirSync(join(root, "notes"), { recursive: true });
  mkdirSync(join(root, "src"), { recursive: true });
  writeFileSync(join(root, "docs", "llms-full.txt"), "full text\n");
  writeFileSync(join(root, "docs", "api", "v1", "index.json"), "{}\n");
  writeFileSync(join(root, "notes", "output.md"), "# Generated by tools/build-notes.js. Do not edit by hand.\nbody\n");
  writeFileSync(join(root, "src", "normal.ts"), "export const value = 1;\n");
  git(root, "add", "-A");
  commit(root, "add outputs");

  const run = runTool(root, "--base", base);
  assert.equal(run.status, 1, run.stderr);
  assert.match(run.stderr, /docs\/llms-full\.txt" is generated at Build time/);
  assert.match(run.stderr, /docs\/api\/v1\/index\.json" is generated at Build time/);
  assert.match(run.stderr, /notes\/output\.md" looks generated/);
  assert.match(run.stderr, /3 generated file\(s\) added/);
  assert.doesNotMatch(run.stderr, /src\/normal\.ts/);
});

test("the command passes a change that adds only hand-written files", () => {
  const root = repository();
  const base = git(root, "rev-parse", "HEAD").trim();
  mkdirSync(join(root, "src"), { recursive: true });
  writeFileSync(join(root, "src", "normal.ts"), "export const value = 1;\n");
  writeFileSync(join(root, "notes.md"), "# Notes\n");
  git(root, "add", "-A");
  commit(root, "add source");

  const run = runTool(root, "--base", base);
  assert.equal(run.status, 0, run.stderr);
  assert.match(run.stdout, /No generated files were added/);
});

test("the command passes a pure rename of a file whose header says it was generated", () => {
  const root = repository();
  writeFileSync(join(root, "pubspec.lock"), '# Generated by pub\nsdks:\n  dart: ">=3.6.0 <4.0.0"\n');
  git(root, "add", "-A");
  commit(root, "add lockfile");
  const base = git(root, "rev-parse", "HEAD").trim();
  git(root, "mv", "pubspec.lock", "pubspec.lock.fixture");
  commit(root, "rename lockfile");

  const run = runTool(root, "--base", base);
  assert.equal(run.status, 0, run.stderr);
  assert.match(run.stdout, /No generated files were added/);
});

test("the command still inspects a rename whose content changed", () => {
  const root = repository();
  writeFileSync(join(root, "pubspec.lock"), '# Generated by pub\nsdks:\n  dart: ">=3.6.0 <4.0.0"\n');
  git(root, "add", "-A");
  commit(root, "add lockfile");
  const base = git(root, "rev-parse", "HEAD").trim();
  git(root, "mv", "pubspec.lock", "pubspec.lock.fixture");
  writeFileSync(
    join(root, "pubspec.lock.fixture"),
    '# Generated by pub\nsdks:\n  dart: ">=3.6.0 <4.0.0"\npackages: {}\n',
  );
  git(root, "add", "-A");
  commit(root, "rename and edit lockfile");

  const run = runTool(root, "--base", base);
  assert.equal(run.status, 1, run.stdout);
  assert.match(run.stderr, /pubspec\.lock\.fixture" looks generated/);
});

test("an unknown base ref exits 2 with the usage line", () => {
  const root = repository();
  const run = runTool(root, "--base", "does-not-exist");
  assert.equal(run.status, 2);
  assert.match(run.stderr, /cannot diff against "does-not-exist"/);
  assert.match(run.stderr, /usage: node tools\/check-generated-files\.mjs/);
});

test("described findings name the regeneration command and the inventory", () => {
  assert.match(
    tool.describeFinding({
      path: "docs/sitemap.xml",
      kind: "path",
      target: "Build time",
      generator: "npm run build:reference",
    }),
    /npm run build:reference.*docs\/generated-files\.md|docs\/generated-files\.md/,
  );
  assert.match(
    tool.describeFinding({ path: "notes/out.md", kind: "marker", marker: "Generated by x" }),
    /notes\/out\.md.*Generated by x/,
  );
});

test("ci.yml runs the guard on pull requests and ci-ok requires it", () => {
  const workflow = parse(readFileSync(workflowPath, "utf8")) as {
    jobs: Record<string, { if?: string; needs?: string[] | string; steps?: { run?: string }[] }>;
  };
  const job = workflow.jobs["generated-files"];
  assert.ok(job, "generated-files is missing from ci.yml");
  assert.match(job.if ?? "", /pull_request/);
  assert.match(job.if ?? "", /merge_group/);
  const commands = (job.steps ?? []).map((step) => step.run ?? "").join("\n");
  assert.match(commands, /tools\/check-generated-files\.mjs/);

  const needs = workflow.jobs["ci-ok"]?.needs;
  const list = Array.isArray(needs) ? needs : needs === undefined ? [] : [needs];
  assert.ok(list.includes("generated-files"), "ci-ok must depend on generated-files");
});
