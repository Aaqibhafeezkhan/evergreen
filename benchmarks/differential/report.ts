// Publishes the differential comparisons as one reviewable artifact: a Markdown page and a JSON file that list every
// disagreement between Evergreen and Renovate, each linked to its evidence. It reads only the committed reports in
// benchmarks/differential/reports/ and the pinned corpus, so it needs no network and no clock.
//
//   node dist/benchmarks/differential/report.js           # rewrites docs/differential-report.md and .json
//   node dist/benchmarks/differential/report.js --check   # exits 1 when either file is out of date

import { readFile, readdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

import type { Comparison, DifferentialReport } from "./renovate.js";

export const REPORTS_DIRECTORY = "benchmarks/differential/reports";
export const MARKDOWN_PATH = "docs/differential-report.md";
export const JSON_PATH = "docs/differential-report.json";

const OUTCOMES = ["agree", "evergreen-only", "renovate-only", "inconclusive"] as const;
type Outcome = (typeof OUTCOMES)[number];

interface CorpusFile {
  repositories: Array<{ repository: string; commit: string }>;
}

export interface Disagreement {
  repository: string;
  outcome: Exclude<Outcome, "agree">;
  family: Comparison["family"];
  path: string;
  name: string;
  evergreen: string[];
  renovate: Comparison["renovate"];
  note: string;
  /** Links that let a reader check the claim: the declaration at the pinned commit and each side's evidence. */
  evidence: Array<{ label: string; url: string }>;
}

export interface DifferentialSummary {
  schemaVersion: "evergreen.differential.summary.v1";
  repositories: Array<{ repository: string; commit: string | null; summary: Record<Outcome, number> }>;
  totals: Record<Outcome, number>;
  disagreements: Disagreement[];
}

const emptyCounts = (): Record<Outcome, number> => ({ agree: 0, "evergreen-only": 0, "renovate-only": 0, inconclusive: 0 });

/** Links for one comparison: the file at the pinned commit, the Evergreen rule page, and Renovate's side. */
export function evidenceFor(repository: string, commit: string | null, item: Comparison): Disagreement["evidence"] {
  const links: Disagreement["evidence"] = [];
  if (commit) links.push({ label: `${item.path} at ${commit.slice(0, 7)}`, url: `https://github.com/${repository}/blob/${commit}/${item.path}` });
  for (const ruleId of item.evergreen) links.push({ label: `Evergreen rule ${ruleId}`, url: `https://github.com/arminazimi/evergreen/blob/main/docs/rules/${ruleId}.md` });
  if (item.renovate === "deprecated" && item.family === "deprecated-package") {
    links.push({ label: `npm deprecation notice for ${item.name}`, url: `https://www.npmjs.com/package/${item.name}` });
  } else if (item.renovate === "skipped") {
    links.push({ label: "Why Renovate skips GitHub lookups without a token", url: "https://docs.renovatebot.com/getting-started/running/#githubcom-token-for-changelogs-and-github-actions" });
  }
  return links;
}

/** Combines the per-repository reports. Repositories and disagreements are sorted, so the output is deterministic. */
export function summarize(reports: readonly DifferentialReport[], commits: ReadonlyMap<string, string>): DifferentialSummary {
  const totals = emptyCounts();
  const disagreements: Disagreement[] = [];
  const repositories = [...reports]
    .sort((left, right) => left.repository.localeCompare(right.repository))
    .map((entry) => {
      const commit = commits.get(entry.repository) ?? null;
      const summary = emptyCounts();
      for (const item of entry.comparisons) {
        summary[item.outcome]++;
        totals[item.outcome]++;
        if (item.outcome === "agree") continue;
        disagreements.push({
          repository: entry.repository,
          outcome: item.outcome,
          family: item.family,
          path: item.path,
          name: item.name,
          evergreen: item.evergreen,
          renovate: item.renovate,
          note: item.note,
          evidence: evidenceFor(entry.repository, commit, item),
        });
      }
      return { repository: entry.repository, commit, summary };
    });
  return { schemaVersion: "evergreen.differential.summary.v1", repositories, totals, disagreements };
}

export function renderMarkdown(summary: DifferentialSummary): string {
  const lines = [
    "# Differential comparison with Renovate",
    "",
    "<!-- Generated by `npm run differential:report`. Do not edit by hand. -->",
    "",
    "Evergreen and Renovate answer different questions, so only the places where both can speak about one dependency in one file are compared (see [Differential testing against Renovate](VALIDATION.md#differential-testing-against-renovate)). Every disagreement below links to its evidence. The same data is in [differential-report.json](differential-report.json).",
    "",
    "| Repository | Agree | Evergreen-only | Renovate-only | Inconclusive |",
    "| --- | --- | --- | --- | --- |",
    ...summary.repositories.map((item) => `| ${item.repository} | ${item.summary.agree} | ${item.summary["evergreen-only"]} | ${item.summary["renovate-only"]} | ${item.summary.inconclusive} |`),
    `| **Total** | ${summary.totals.agree} | ${summary.totals["evergreen-only"]} | ${summary.totals["renovate-only"]} | ${summary.totals.inconclusive} |`,
  ];
  const titles: Record<Exclude<Outcome, "agree">, string> = {
    "evergreen-only": "Evergreen only",
    "renovate-only": "Renovate only",
    inconclusive: "Inconclusive",
  };
  for (const outcome of ["evergreen-only", "renovate-only", "inconclusive"] as const) {
    const items = summary.disagreements.filter((item) => item.outcome === outcome);
    lines.push("", `## ${titles[outcome]} (${items.length})`, "");
    if (items.length === 0) {
      lines.push("None.");
      continue;
    }
    for (const item of items) {
      lines.push(`- **${item.repository}** \`${item.path}\` — ${item.family} \`${item.name}\`: ${item.note}`);
      lines.push(`  Evidence: ${item.evidence.map((link) => `[${link.label}](${link.url})`).join("; ") || "none"}`);
    }
  }
  return `${lines.join("\n")}\n`;
}

export async function build(root = "."): Promise<{ markdown: string; json: string }> {
  const directory = resolve(root, REPORTS_DIRECTORY);
  const names = (await readdir(directory)).filter((name) => name.endsWith(".json")).sort();
  const reports = await Promise.all(names.map(async (name) => JSON.parse(await readFile(resolve(directory, name), "utf8")) as DifferentialReport));
  const corpus = JSON.parse(await readFile(resolve(root, "benchmarks/public-repositories.json"), "utf8")) as CorpusFile;
  const summary = summarize(reports, new Map(corpus.repositories.map((entry) => [entry.repository, entry.commit])));
  return { markdown: renderMarkdown(summary), json: `${JSON.stringify(summary, null, 2)}\n` };
}

export async function main(argv: readonly string[] = process.argv.slice(2)): Promise<number> {
  const { markdown, json } = await build();
  const files = [{ path: MARKDOWN_PATH, text: markdown }, { path: JSON_PATH, text: json }];
  if (argv.includes("--check")) {
    let stale = false;
    for (const file of files) {
      const current = await readFile(resolve(file.path), "utf8").catch(() => "");
      if (current !== file.text) {
        console.error(`${file.path} is out of date. Run: npm run differential:report`);
        stale = true;
      }
    }
    return stale ? 1 : 0;
  }
  for (const file of files) await writeFile(resolve(file.path), file.text);
  console.log(`Wrote ${MARKDOWN_PATH} and ${JSON_PATH}.`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.exitCode = await main();
