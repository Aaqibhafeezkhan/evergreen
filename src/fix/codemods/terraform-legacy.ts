import {
  parseTerraformLegacy,
  type TerraformInterpolationOnlyDeclaration,
  type TerraformLegacyDeclaration,
  type TerraformLegacyFunctionDeclaration,
} from "../../detectors/terraform/parse-terraform.js";
import type { Finding, ScanResult } from "../../domain.js";
import { required } from "../../required.js";
import type { FilePatch, Fixer, Refuse } from "../types.js";
import { type Edit, diffFor } from "./shared/edits.js";
import { newlineReason, readRepositoryText } from "./shared/source.js";

const INTERPOLATION_RULE_ID = "terraform.syntax.interpolation-only";
const LEGACY_FUNCTION_RULE_ID = "terraform.function.list-map";
/** A short header that says a tool owns the file; rewriting it would be undone by the next generation. */
const GENERATED =
  /^\s*(?:#|\/\/)\s*(?:code generated\b|this file (?:is|was) generated\b|generated by\b|auto-generated\b|do not edit\b)/im;
const OBJECT_KEY = /^[A-Za-z_][A-Za-z0-9_-]*$/;
const QUOTED_KEY = /^"(?:[^"\\]|\\.)*"$/;

interface Target {
  finding: Finding;
  kind: "interpolation" | "function";
  /** The function name the finding was reported at; unused for an interpolation. */
  name?: "list" | "map";
}

/** True when the finding belongs to one of the two rules this codemod repairs. */
function isLegacyFinding(finding: Finding): boolean {
  return (
    finding.detector === "terraform" &&
    (finding.ruleId === INTERPOLATION_RULE_ID || finding.ruleId === LEGACY_FUNCTION_RULE_ID)
  );
}

/** Why the call cannot be rewritten exactly, or the replacement that keeps its arguments as written. */
function functionEdit(declaration: TerraformLegacyFunctionDeclaration): { replacement: string } | { reason: string } {
  if (!declaration.oneLine) return { reason: "The call's arguments are not all on one line." };
  if (declaration.name === "list") {
    if (declaration.arguments.length === 0) return { reason: "The list() call has no arguments." };
    return { replacement: `tolist([${declaration.arguments.join(", ")}])` };
  }
  if (declaration.arguments.length < 2 || declaration.arguments.length % 2 !== 0) {
    return { reason: "The map() call does not have an even number of arguments." };
  }
  const pairs: string[] = [];
  for (let index = 0; index < declaration.arguments.length; index += 2) {
    const key = required(declaration.arguments[index], "the map key");
    if (!OBJECT_KEY.test(key) && !QUOTED_KEY.test(key)) {
      return { reason: "The map() key is not a quoted string or an identifier." };
    }
    pairs.push(`${key} = ${required(declaration.arguments[index + 1], "the map value")}`);
  }
  return { replacement: `tomap({${pairs.join(", ")}})` };
}

/** Why the string cannot lose its quotes, or the expression that replaces it. */
function interpolationEdit(
  declaration: TerraformInterpolationOnlyDeclaration,
): { replacement: string } | { reason: string } {
  if (declaration.context === "key")
    return { reason: "The string is an object key; removing its quotes would change the key syntax." };
  if (declaration.context === "label")
    return { reason: "The string is a block label; removing its quotes would not be valid HCL." };
  return { replacement: declaration.expression };
}

function reasonOf(declaration: TerraformLegacyDeclaration): string {
  if (declaration.kind === "interpolation_only") {
    const edit = interpolationEdit(declaration);
    return "reason" in edit ? edit.reason : "The string is not exactly one interpolation-only expression.";
  }
  const edit = functionEdit(declaration);
  return "reason" in edit ? edit.reason : "The call was not rewritten.";
}

/** The declaration a finding was reported at, or undefined when the line no longer holds it. */
function declarationFor(
  declarations: readonly TerraformLegacyDeclaration[],
  target: Target,
): TerraformLegacyDeclaration | undefined {
  const line = target.finding.location.line;
  const column = target.finding.location.column;
  const matches = declarations.filter(
    (declaration) =>
      declaration.line === line &&
      (target.kind === "interpolation"
        ? declaration.kind === "interpolation_only"
        : declaration.kind === "legacy_function" && (target.name === undefined || declaration.name === target.name)),
  );
  // An edit earlier on the line moves later columns; the exact column wins, then the only candidate.
  return (
    matches.find((declaration) => declaration.column === column) ?? (matches.length === 1 ? matches[0] : undefined)
  );
}

/** Apply the non-overlapping edits right to left; a nested edit waits for the next pass. */
function applyEdits(line: string, edits: readonly Edit[]): string {
  let text = line;
  let boundary = Number.POSITIVE_INFINITY;
  for (const edit of [...edits].sort((left, right) => right.start - left.start)) {
    if (edit.end > boundary) continue;
    text = text.slice(0, edit.start) + edit.replacement + text.slice(edit.end);
    boundary = edit.start;
  }
  return text;
}

/** Every rewrite a target line allows in this pass, keyed by the declaration it came from. */
function lineEdits(
  line: string,
  declarations: readonly TerraformLegacyDeclaration[],
  targets: readonly Target[],
): Edit[] {
  const edits: Edit[] = [];
  for (const declaration of declarations) {
    if (declaration.line !== required(targets[0], "the line target").finding.location.line) continue;
    const target = targets.find((candidate) =>
      candidate.kind === "interpolation"
        ? declaration.kind === "interpolation_only"
        : declaration.kind === "legacy_function" && declaration.name === candidate.name,
    );
    if (!target) continue;
    const edit = declaration.kind === "interpolation_only" ? interpolationEdit(declaration) : functionEdit(declaration);
    if ("reason" in edit) continue;
    const start = declaration.column - 1;
    const end =
      declaration.kind === "interpolation_only"
        ? start + declaration.value.length
        : start + declaration.end - declaration.start;
    if (line.slice(start, end) === edit.replacement) continue;
    edits.push({ start, end, replacement: edit.replacement });
  }
  return edits;
}

/** Refuse a file whose header says another tool generates it. */
function generated(contents: string): boolean {
  return GENERATED.test(contents.split(/\r?\n/).slice(0, 5).join("\n"));
}

/**
 * Rewrites the two Terraform language forms removed in 0.15: an interpolation-only string loses its quotes and
 * `list(a, b)` and `map(k, v)` become `tolist([a, b])` and `tomap({ k = v })`. A heredoc is never read, a string
 * with text outside one interpolation is not an interpolation-only expression, and files under `.terraform/` or
 * with a generated header are left alone. A call whose arguments span lines, a `list()` without arguments, a
 * `map()` without key/value pairs, a map key that is not a string or identifier, and a string used as an object
 * key or block label are refused with the reason instead of guessed.
 */
export const terraformLegacyFixer: Fixer = {
  id: "terraform-legacy",
  async plan(result, refuse) {
    const byPath = groupByPath(result, refuse);
    const patches: FilePatch[] = [];
    for (const [path, findings] of [...byPath].sort(([left], [right]) => left.localeCompare(right))) {
      const patch = await planFile(result.root, path, findings, refuse);
      if (patch !== undefined) patches.push(patch);
    }
    return patches;
  },
};

/** The legacy findings the codemod may rewrite, grouped by file; a finding it cannot reach is refused on the spot. */
function groupByPath(result: ScanResult, refuse: Refuse | undefined): Map<string, Finding[]> {
  const byPath = new Map<string, Finding[]>();
  for (const finding of result.findings) {
    if (!isLegacyFinding(finding)) continue;
    const reason = unreachableReason(finding);
    if (reason !== undefined) {
      refuse?.(finding, reason);
      continue;
    }
    const existing = byPath.get(finding.location.path) ?? [];
    existing.push(finding);
    byPath.set(finding.location.path, existing);
  }
  return byPath;
}

/** Why a legacy finding cannot be rewritten at all, or undefined when it can be. */
function unreachableReason(finding: Finding): string | undefined {
  if (finding.location.path.split("/").includes(".terraform")) {
    return "The file is inside .terraform/, which Terraform generates.";
  }
  if (finding.location.line === undefined) return "The finding names no line to rewrite.";
  return undefined;
}

/** The patch for one file's findings, or undefined when no line changes. Every refusal is reported. */
async function planFile(
  root: string,
  path: string,
  findings: readonly Finding[],
  refuse: Refuse | undefined,
): Promise<FilePatch | undefined> {
  const source = await readTerraformSource(root, path);
  if ("reason" in source) {
    for (const finding of findings) refuse?.(finding, source.reason);
    return undefined;
  }
  const before = source.text;
  const targets = targetsIn(before, findings);
  const text = rewriteToStability(before, targets);
  reportRemaining(before, text, targets, refuse);
  return diffFor(path, before, text);
}

/** The file's text, or the reason the file cannot be rewritten. */
async function readTerraformSource(root: string, path: string): Promise<{ text: string } | { reason: string }> {
  const source = await readRepositoryText(root, path, "Terraform file");
  if ("reason" in source) return source;
  if (generated(source.text)) return { reason: "The file says another tool generates it." };
  const missing = newlineReason(source.text, "Terraform file");
  return missing === undefined ? source : { reason: missing };
}

/** Each finding as a target, with the function name of a legacy call resolved from the file as it is now. */
function targetsIn(text: string, findings: readonly Finding[]): Target[] {
  const initial = parseTerraformLegacy(text);
  return findings.map((finding) => {
    const target: Target = {
      finding,
      kind: finding.ruleId === INTERPOLATION_RULE_ID ? "interpolation" : "function",
    };
    const declaration = declarationFor(initial, target);
    if (declaration?.kind === "legacy_function") target.name = declaration.name;
    return target;
  });
}

/** One pass cannot apply an edit nested inside another, as in "${list("a")}"; repeat until nothing moves. */
function rewriteToStability(before: string, targets: readonly Target[]): string {
  let text = before;
  for (let pass = 0; pass < 8; pass++) {
    const next = rewritePass(text, targets);
    if (next === undefined) break;
    text = next;
  }
  return text;
}

/** One pass over the lines the targets name; undefined when no line changes. */
function rewritePass(text: string, targets: readonly Target[]): string | undefined {
  const declarations = parseTerraformLegacy(text);
  const lines = text.split("\n");
  let changed = false;
  for (const lineNumber of new Set(targets.map((target) => required(target.finding.location.line, "the line")))) {
    const lineTargets = targets.filter((target) => target.finding.location.line === lineNumber);
    const edits = lineEdits(lines[lineNumber - 1] ?? "", declarations, lineTargets);
    if (edits.length === 0) continue;
    lines[lineNumber - 1] = applyEdits(lines[lineNumber - 1] ?? "", edits);
    changed = true;
  }
  return changed ? lines.join("\n") : undefined;
}

/** Refuses each finding whose legacy syntax survives the rewrite, with the reason the remaining declaration gives. */
function reportRemaining(before: string, text: string, targets: readonly Target[], refuse: Refuse | undefined): void {
  const original = before.split("\n");
  const after = text.split("\n");
  const final = parseTerraformLegacy(text);
  for (const target of targets) {
    const index = required(target.finding.location.line, "the line") - 1;
    const declaration = declarationFor(final, target);
    if (declaration) {
      refuse?.(target.finding, reasonOf(declaration));
    } else if (after[index] === original[index]) {
      refuse?.(target.finding, "The line no longer holds the legacy syntax the finding names.");
    }
  }
}
