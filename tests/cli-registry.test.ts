import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { readdir, readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { test } from "node:test";

import { commands } from "../src/commands/index.generated.js";
import { COMMANDS, completionShells, renderCompletions, renderHelp } from "../src/completions.js";
import { runCli } from "./cli-runner.js";

const fixture = (name: string) => readFile(resolve("tests/fixtures/cli", name), "utf8");

test("help text matches the committed snapshot", async () => {
  assert.equal(renderHelp(commands), await fixture("help.txt"));
});

test("completion scripts match the committed snapshots", async () => {
  assert.equal(renderCompletions("bash"), await fixture("completions.bash"));
  assert.equal(renderCompletions("zsh"), await fixture("completions.zsh"));
  assert.equal(renderCompletions("fish"), await fixture("completions.fish"));
});

test("the CLI --help and completion commands match the snapshots", async () => {
  assert.equal((await runCli(["--help"])).stdout, renderHelp(commands));
  for (const shell of completionShells)
    assert.equal((await runCli(["completions", shell])).stdout, renderCompletions(shell));
});

test("every command module is registered and the generated index is current", async () => {
  const excluded = new Set(["types.ts", "runtime.ts", "registry.ts", "index.generated.ts"]);
  const files = (await readdir(resolve("src/commands")))
    .filter((name) => name.endsWith(".ts") && !excluded.has(name))
    .sort();
  const generated = await readFile(resolve("src/commands/index.generated.ts"), "utf8");
  assert.match(generated, /^\/\/ Generated by tools\/generate-commands-index\.mjs\. Do not edit by hand\./);
  for (const file of files) {
    const imported = `"./${file.replace(/\.ts$/, ".js")}"`;
    assert.ok(generated.includes(imported), `${file} is not imported by the command index`);
  }
  const check = spawnSync(process.execPath, ["tools/generate-commands-index.mjs", "--check"], { encoding: "utf8" });
  assert.equal(check.status, 0, check.stderr);
  assert.equal(new Set(commands.map((command) => command.name)).size, commands.length);
  assert.ok(commands.length >= 30);
  for (const spec of COMMANDS)
    assert.ok(
      commands.some((command) => command.name === spec.name),
      spec.name,
    );
});
