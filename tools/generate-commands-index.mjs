// Lists src/commands/*.ts command modules and writes src/commands/index.generated.ts.
// Infrastructure modules are not commands. Run with --check to fail when the file drifted.

import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const directory = join(root, "src", "commands");
const output = join(directory, "index.generated.ts");

/** Shared modules. `context.ts` is the `context` command; the context type lives in `types.ts`. */
const excluded = new Set(["types.ts", "runtime.ts", "registry.ts", "index.generated.ts"]);

const reserved = new Set([
  "break",
  "case",
  "catch",
  "class",
  "const",
  "continue",
  "debugger",
  "default",
  "delete",
  "do",
  "else",
  "enum",
  "export",
  "extends",
  "false",
  "finally",
  "for",
  "function",
  "if",
  "implements",
  "import",
  "in",
  "instanceof",
  "interface",
  "let",
  "new",
  "null",
  "package",
  "private",
  "protected",
  "public",
  "return",
  "static",
  "super",
  "switch",
  "this",
  "throw",
  "true",
  "try",
  "typeof",
  "var",
  "void",
  "while",
  "with",
  "yield",
]);

export function aliasFor(filename) {
  const alias = filename.replace(/\.ts$/, "").replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
  return reserved.has(alias) ? `${alias}Command` : alias;
}

export async function commandFiles() {
  const entries = await readdir(directory);
  return entries
    .filter((name) => name.endsWith(".ts") && !excluded.has(name))
    .sort((left, right) => (left < right ? -1 : left > right ? 1 : 0));
}

export function renderIndex(files) {
  const rows = files.map((filename) => ({ filename, alias: aliasFor(filename) }));
  const aliases = new Set();
  for (const row of rows) {
    if (aliases.has(row.alias)) throw new Error(`Command modules alias to the same binding: ${row.alias}`);
    aliases.add(row.alias);
  }
  const imports = rows
    .map((row) => `import { command as ${row.alias} } from "./${row.filename.replace(/\.ts$/, ".js")}";`)
    .join("\n");
  const list = rows.map((row) => `  ${row.alias},`).join("\n");
  return `// Generated by tools/generate-commands-index.mjs. Do not edit by hand.
import type { CliCommand } from "./types.js";
${imports}

export const commands: readonly CliCommand[] = [
${list}
];
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const files = await commandFiles();
  const next = renderIndex(files);
  if (process.argv.includes("--check")) {
    const current = await readFile(output, "utf8").catch(() => "");
    if (current !== next) {
      process.stderr.write(
        "src/commands/index.generated.ts is out of date. Run: node tools/generate-commands-index.mjs\n",
      );
      process.exitCode = 1;
    }
  } else {
    await writeFile(output, next);
  }
}
